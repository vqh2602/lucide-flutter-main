import 'dart:convert';
import 'dart:io';

import 'package:recase/recase.dart';

void main(List<String> args) {
  final repoRoot = findRepoRoot();

  File fontsPreviewFile;
  if (args.isNotEmpty) {
    fontsPreviewFile = File(args[0]);
    if (!fontsPreviewFile.isAbsolute) {
      fontsPreviewFile = File('${Directory.current.path}/${args[0]}');
    }
  } else {
    fontsPreviewFile = File('${repoRoot.path}/assets/info.json');
  }

  if (!fontsPreviewFile.existsSync()) {
    print('lucide preview file not found: ${fontsPreviewFile.path}');
    exit(1);
  }

  String content = fontsPreviewFile.readAsStringSync();
  Map<String, dynamic> jsonMap = json.decode(content);

  List<Map<dynamic, dynamic>> resultList = jsonMap.entries
      .map((entry) => {'name': entry.key, ...entry.value})
      .toList();

  final sourceDir = Directory('${repoRoot.path}/tool/lucide/lucide-source');
  final weights = [100, 200, 300, 400, 500, 600];
  final weightDirs = {
    for (final w in weights)
      w: Directory('${repoRoot.path}/tool/lucide/svg_input/weight$w'),
  };

  const String fallbackSvg =
      '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="#ff0000" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="10"/><line x1="12" y1="8" x2="12" y2="16"/><line x1="8" y1="12" x2="12" y2="12"/></svg>';

  // 1. Regular icon library: lib/lucide_icons.dart
  List<String> regularOutput = [
    "library lucide_icons;\n\n",
    "import \"package:flutter/widgets.dart\";\n\n",
    "// THIS FILE IS AUTOMATICALLY GENERATED!\n\n",
    "/// Lucide Icons (Regular Weight)\n",
    "@staticIconProvider\n",
    "class LucideIcons {\n",
    "  /// Private constructor to prevent instantiation.\n",
    "  /// This class is intended solely for organizing static icon definitions.\n",
    "  /// Making the constructor private stops the IDE from suggesting object creation.\n",
    "  const LucideIcons._();\n\n",
  ];

  // 2. Weight icon libraries: lib/lucide_icons_100.dart ... lib/lucide_icons_600.dart
  final Map<int, List<String>> weightOutputs = {
    for (final w in weights)
      w: [
        "library lucide_icons_$w;\n\n",
        "import \"package:flutter/widgets.dart\";\n\n",
        "// THIS FILE IS AUTOMATICALLY GENERATED!\n\n",
        "/// Lucide Icons (Weight $w)\n",
        "@staticIconProvider\n",
        "class LucideIcons$w {\n",
        "  /// Private constructor to prevent instantiation.\n",
        "  /// This class is intended solely for organizing static icon definitions.\n",
        "  /// Making the constructor private stops the IDE from suggesting object creation.\n",
        "  const LucideIcons$w._();\n\n",
      ],
  };

  // 3. Test list: lib/test_icons.dart
  List<String> listIconTest = [
    "import 'package:flutter/material.dart';\n",
    "import 'package:lucide_icons_flutter/lucide_icons.dart';\n",
    "import 'package:lucide_icons_flutter/lucide_icons_weights.dart';\n\n",
    "/// Lucide Icons\n",
    "const List<IconData> icons = ["
  ];
  List<String> listIconNamesTest = ["\n\nconst List<String> iconNames = ["];

  final generatedIconNames = <String>{};

  for (Map data in resultList) {
    String iconName = data['name'];
    final baseName = ReCase(iconName).camelCase;
    final codePoint = parseUnicodeString(data['unicode']);

    if (!generatedIconNames.add(baseName)) {
      print('Bỏ qua icon trùng tên Dart: $iconName -> $baseName');
      continue;
    }

    final rawName = iconName.replaceAll('icon-', '');

    // 1. Regular icon
    final regularSvgFile = File('${sourceDir.path}/$rawName.svg');
    final regularSvgBase64 = encodeSvg(regularSvgFile, fallbackSvg);

    regularOutput.add(
      "  /// ${data['name']}\n"
      "  /// ![${data['name']}](data:image/svg+xml;base64,$regularSvgBase64)\n"
      "  static const IconData $baseName = const IconData($codePoint, fontFamily: 'Lucide', fontPackage: 'lucide_icons_flutter');\n"
      "  static const IconData ${baseName}Dir = const IconData($codePoint, fontFamily: 'Lucide', fontPackage: 'lucide_icons_flutter', matchTextDirection: true);\n\n",
    );

    listIconTest.add("\n  LucideIcons.$baseName,");
    listIconNamesTest.add("\n  '$baseName',");

    // 2. Weights 100 -> 600
    for (final w in weights) {
      final weightSvgFile = File('${weightDirs[w]!.path}/$rawName.svg');
      final weightSvgBase64 = encodeSvg(weightSvgFile, fallbackSvg);

      weightOutputs[w]!.add(
        "  /// ${data['name']} với fontFamily Lucide$w\n"
        "  /// ![${data['name']}](data:image/svg+xml;base64,$weightSvgBase64)\n"
        "  static const IconData $baseName = const IconData($codePoint, fontFamily: 'Lucide$w', fontPackage: 'lucide_icons_flutter');\n"
        "  static const IconData ${baseName}Dir = const IconData($codePoint, fontFamily: 'Lucide$w', fontPackage: 'lucide_icons_flutter', matchTextDirection: true);\n\n",
      );

      listIconTest.add("\n  LucideIcons$w.$baseName,");
      listIconNamesTest.add("\n  '$baseName$w',");
    }
  }

  regularOutput.add("}\n");

  for (final w in weights) {
    weightOutputs[w]!.add("}\n");
  }


  listIconTest.add("\n];");
  listIconNamesTest.add("\n];\n");

  final libDir = Directory('${repoRoot.path}/lib');
  if (!libDir.existsSync()) {
    libDir.createSync(recursive: true);
  }

  // Write lib/lucide_icons.dart
  File('${libDir.path}/lucide_icons.dart')
      .writeAsStringSync(regularOutput.join());
  print('Generated ${libDir.path}/lucide_icons.dart');

  // Write lib/lucide_icons_$w.dart
  for (final w in weights) {
    File('${libDir.path}/lucide_icons_$w.dart')
        .writeAsStringSync(weightOutputs[w]!.join());
    print('Generated ${libDir.path}/lucide_icons_$w.dart');
  }

  // Write lib/lucide_icons_weights.dart
  final umbrellaContent = StringBuffer()
    ..writeln('library lucide_icons_weights;\n');
  for (final w in weights) {
    umbrellaContent.writeln("export 'lucide_icons_$w.dart';");
  }
  File('${libDir.path}/lucide_icons_weights.dart')
      .writeAsStringSync(umbrellaContent.toString());
  print('Generated ${libDir.path}/lucide_icons_weights.dart');

  // Write lib/test_icons.dart
  File('${libDir.path}/test_icons.dart')
      .writeAsStringSync(listIconTest.join() + listIconNamesTest.join());
  print('Generated ${libDir.path}/test_icons.dart');
}

String encodeSvg(File file, String fallbackSvg) {
  String svgContent = '';
  try {
    if (file.existsSync()) {
      svgContent = file.readAsStringSync();
      svgContent = svgContent
          .replaceAll('stroke="currentColor"', 'stroke="#0066cc"')
          .replaceAll('width="24"', 'width="48"')
          .replaceAll('height="24"', 'height="48"');

      if (!svgContent.contains('xmlns="http://www.w3.org/2000/svg"')) {
        svgContent = svgContent.replaceFirst(
            '<svg', '<svg xmlns="http://www.w3.org/2000/svg"');
      }

      svgContent = svgContent.replaceFirst('<svg', '<svg version="1.1"');
      return base64Encode(utf8.encode(svgContent));
    }
  } catch (e) {
    print('Cannot read SVG ${file.path}: $e');
  }

  return base64Encode(utf8.encode(fallbackSvg));
}

int parseUnicodeString(String unicodeString) {
  String hexString = unicodeString.substring(2, unicodeString.length - 1);
  int unicodeInt = int.parse(hexString);
  return unicodeInt;
}

int parseUnicodeString2(String unicodeString) {
  String hexString = unicodeString.substring(2);
  int unicodeInt = int.parse(hexString, radix: 16);
  return unicodeInt;
}

Directory findRepoRoot() {
  var current = Directory.current.absolute;
  while (true) {
    if (File('${current.path}/pubspec.yaml').existsSync()) {
      return current;
    }
    final parent = current.parent;
    if (parent.path == current.path) {
      throw StateError('pubspec.yaml not found to determine repo root.');
    }
    current = parent;
  }
}
